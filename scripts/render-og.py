#!/usr/bin/env python3
"""Render assets/og-card.png, the Open Graph link card.

One static image, regenerated by hand when the wording changes. Crawlers fetch it
and readers never do, so it does not enter the page budgets measured by
measure-pages.py; it does follow the same palette and the same two faces the site
itself serves, so a link preview shows the site the reader will then land on.
Committed like the type specimens were, not regenerated by the ordinary build.

Invariants worth failing loudly, learned from the preload that failed silently
(AGENT.md section 7, gotcha 13): every line must fit inside the card, and nothing
may spill out of it. The script asserts both before writing the file."""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent

FACES = {
    "heading": ROOT / "fontok/arsenal/Arsenal-Bold.ttf",
    "body": ROOT / "fontok/General Sans/OTF/GeneralSans-Medium.otf",
    "muted": ROOT / "fontok/General Sans/OTF/GeneralSans-Regular.otf",
}
# Same tokens as assets/css/main.css, read as RGB triples.
SKY = (224, 244, 252)
SHEET = (248, 253, 255)
HEADING = (27, 77, 104)
INK = (56, 63, 74)
MUTED = (88, 96, 104)
ACCENT = (10, 108, 147)

SIZE = (1200, 630)
SHEET_BOX = (96, 88, 1104, 542)
MARGIN_LEFT = 150
RIGHT_LIMIT = 1056
BOTTOM_LIMIT = 542


def font(name: str, size: int) -> ImageFont.FreeTypeFont:
    path = FACES[name]
    if not path.exists():
        raise SystemExit(f"render-og: {path} is missing; the card needs the "
                         "site's own faces, not substitutes")
    return ImageFont.truetype(str(path), size)


def line(draw: ImageDraw.ImageDraw, xy: tuple[int, int], text: str,
         face: ImageFont.FreeTypeFont, color: tuple[int, int, int],
         lines_seen: list[tuple[str, tuple[int, int, int, int]]]) -> None:
    box = draw.textbbox(xy, text, font=face)
    label = f"{text!r} at {box}"
    lines_seen.append((label, box))
    draw.text(xy, text, font=face, fill=color)


def main() -> None:
    img = Image.new("RGB", SIZE, SKY)
    draw = ImageDraw.Draw(img)
    draw.rounded_rectangle(SHEET_BOX, radius=24, fill=SHEET)

    seen: list[tuple[str, tuple[int, int, int, int]]] = []
    line(draw, (MARGIN_LEFT, 128), "The Third Party", font("heading", 96), HEADING, seen)
    draw.rectangle((MARGIN_LEFT, 268, MARGIN_LEFT + 320, 276), fill=ACCENT)
    line(draw, (MARGIN_LEFT, 304), "The web is more extractive than it looks.",
         font("body", 38), INK, seen)
    line(draw, (MARGIN_LEFT, 372), "Once for the site. Once for the reader.",
         font("muted", 30), MUTED, seen)
    line(draw, (MARGIN_LEFT, 412), "Once for whoever paid for it.",
         font("muted", 30), MUTED, seen)
    line(draw, (MARGIN_LEFT, 466), "third-party.statichost.page",
         font("body", 26), HEADING, seen)

    for label, (left, top, right, bottom) in seen:
        if right > RIGHT_LIMIT or bottom > BOTTOM_LIMIT:
            raise SystemExit(f"render-og: text would spill out of the card: {label}")

    out = ROOT / "assets/og-card.png"
    img.save(out, optimize=True)
    size = out.stat().st_size
    print(f"render-og: wrote {out.relative_to(ROOT)} ({size} bytes, "
          f"drawn with Arsenal and General Sans)")


if __name__ == "__main__":
    main()
